# Create a function that uses a for loop and multiplies and 
# prints a set of numbers by 3. 
# The numbers should be from 1 to 1500. 
# You can use a list or range()

def multiply_3x():
    numbers_B = range(1, 1501)
    for i in numbers_B:
        print(i * 3)

